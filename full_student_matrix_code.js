function exportStudentsMatrixXLSX() {
  ensureStudentProfiles();
  const headers = [
    'N°', 'NOMBRES Y APELLIDOS DEL ESTUDIANTE', 'N° CÉDULA', 'FECHA DE NACIMIENTO', 'EDAD',
    'TIENE NN.EE ASOCIADA O NO A LA DISCAPACIDAD', 'TIENE ALGUNA ENFERMEDAD', 'TIENE OTROS HERMANOS EN LA INSTITUCIÓN EN QUE AÑO Y PARALELO',
    'NOMBRES Y APELLIDOS DEL REPRESENTANTE LEGAL', 'N° CÉDULA', 'NUMEROS TELEFÓNICOS', 'DIRECCION DOMICILIARIA',
    'CORREO ELECTRONICO', 'NUMEROS TELEFÓNICOS EN CASO DE EMERGENCIA',
    'NOMBRE Y APELLIDO DE LA MADRE', 'N° DE CÉDULA', 'TELÉFONO',
    'NOMBRE Y APELLIDO DEL PADRE', 'N° DE CÉDULA', 'TELÉFONO'
  ];

  const rows = S.studentProfiles.map((p, idx) => [
    (idx + 1).toString(),
    p.nombre || S.students[idx] || '',
    p.cedula || '',
    p.fecha_nacimiento || '',
    p.edad || calculateAgeFromBirthDate(p.fecha_nacimiento) || '',
    p.nnee || 'NO',
    p.enfermedad || 'NO',
    p.hermanos_inst || 'NO',
    p.rep_nombre || '',
    p.rep_cedula || '',
    p.rep_telefono || '',
    p.direccion || '',
    p.rep_email || '',
    p.tel_emergencia || '',
    p.madre_nombre || '',
    p.madre_cedula || '',
    p.madre_telefono || '',
    p.padre_nombre || '',
    p.padre_cedula || '',
    p.padre_telefono || ''
  ]);

  const sheets = [{
    name: 'MATRIZ ESTUDIANTES',
    rows: [headers, ...rows]
  }];

  const bytes = makeXLSX(sheets);
  const blob = new Blob([bytes], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  const fileName = 'Matriz_Datos_Estudiantes_' + (S.grado || 'Sexto_C').replace(/\s+/g, '_') + '_' + (S.anio || '2025-2026') + '.xlsx';
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
  toast('✔ Matriz de Estudiantes exportada a Excel (.xlsx)', '#16a34a');
}
