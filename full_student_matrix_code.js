function calculateAgeFromBirthDate(birthDateStr) {
  if (!birthDateStr) return '';
  const d = new Date(birthDateStr);
  if (isNaN(d.getTime())) return '';
  const now = new Date();
  let years = now.getFullYear() - d.getFullYear();
  let months = now.getMonth() - d.getMonth();
  let days = now.getDate() - d.getDate();

  if (days < 0) {
    months--;
    const prevMonth = new Date(now.getFullYear(), now.getMonth(), 0);
    days += prevMonth.getDate();
  }
  if (months < 0) {
    years--;
    months += 12;
  }
  if (years < 0) return '';
  return years + ' años, ' + months + ' meses, ' + days + ' días';
}

function formatPhoneWhatsApp(phoneStr) {
  if (!phoneStr) return '';
  const clean = String(phoneStr).replace(/[^0-9]/g, '');
  if (!clean) return phoneStr;
  let intl = clean;
  if (intl.startsWith('0')) intl = '593' + intl.substring(1);
  else if (!intl.startsWith('593') && intl.length === 9) intl = '593' + intl;
  return intl;
}

